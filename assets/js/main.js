/* ========================================================
   UPDATE QUANTITY
======================================================== */

function updateQuantity(serviceId, change) {

  let serviceItem = null;


  /* ================= FIND SERVICE ================= */

  for (const category in servicesData) {

    const found = servicesData[category].find(
      (service) => service.id === serviceId
    );

    if (found) {

      serviceItem = found;

      break;

    }

  }


  if (!serviceItem) return;


  /* ================= CURRENT QUANTITY ================= */

  const currentQty = cart[serviceId]
    ? cart[serviceId].qty
    : 0;


  /* ================= NEW QUANTITY ================= */

  const newQty = currentQty + change;


  /* ================= REMOVE ITEM ================= */

  if (newQty <= 0) {

    delete cart[serviceId];

  }


  /* ================= ADD / UPDATE ITEM ================= */

  else {

    cart[serviceId] = {
      ...serviceItem,
      qty: newQty,
    };

  }


  /* ================= RE-RENDER ================= */

  renderCards();

}


/* ========================================================
   SWITCH CATEGORY
======================================================== */

function switchCategory(category) {

  activeCategory = category;


  const categories = [
    "salon",
    "hydraglo",
    "laser"
  ];


  categories.forEach((cat) => {

    const tabBtn =
      document.getElementById(`tab-${cat}`);


    if (!tabBtn) return;


    /* ================= ACTIVE ================= */

    if (cat === category) {

      tabBtn.className =
        `
        px-5 py-2.5
        rounded-full
        text-sm
        font-semibold
        transition-all
        duration-200
        whitespace-nowrap
        bg-primary-light
        text-primary
        shadow-xs
        border
        border-pink-200/50
        `;

    }


    /* ================= INACTIVE ================= */

    else {

      tabBtn.className =
        `
        px-5 py-2.5
        rounded-full
        text-sm
        font-medium
        transition-all
        duration-200
        whitespace-nowrap
        bg-gray-100
        text-gray-600
        hover:bg-gray-200
        `;

    }

  });


  /* ================= RENDER ================= */

  renderCards();

}


/* ========================================================
   UPDATE CART SUMMARY
   + MOBILE BOOKING BADGE
======================================================== */

function updateCartSummary() {

  const badgeEl =
    document.getElementById("mobileBookingBadge");

  const totalPriceEl =
    document.getElementById("cartTotalPrice");

  const itemsLabelEl =
    document.getElementById("cartItemsLabel");


  let totalItems = 0;

  let totalPrice = 0;


  /* ================= CALCULATE CART ================= */

  Object.values(cart).forEach((item) => {

    totalItems += item.qty;

    totalPrice += item.price * item.qty;

  });


  /* ================= PRICE ================= */

  if (totalPriceEl) {

    totalPriceEl.innerText =
      `₹${totalPrice.toLocaleString("en-IN")}`;

  }


  /* ================= ITEMS ================= */

  if (itemsLabelEl) {

    itemsLabelEl.innerText =
      `${totalItems} item${totalItems === 1 ? "" : "s"}`;

  }


  /* ====================================================
     MOBILE BOOKING BADGE
  ==================================================== */

  if (!badgeEl) return;


  /* ================= SHOW ================= */

  if (totalItems > 0) {

    /* Set Count */

    badgeEl.innerText = totalItems;


    /* Show Badge */

    badgeEl.classList.remove("hidden");


    /* Restart Animation */

    badgeEl.classList.remove("badge-pop");

    void badgeEl.offsetWidth;

    badgeEl.classList.add("badge-pop");

  }


  /* ================= HIDE ================= */

  else {

    badgeEl.classList.add("hidden");

  }

}


